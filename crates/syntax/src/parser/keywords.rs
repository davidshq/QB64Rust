/// Whether `name` (without a type suffix) is a reserved word, ASCII case ignored.
pub fn is_keyword(name: &[u8]) -> bool {
    KEYWORDS.iter().any(|k| k.as_bytes().eq_ignore_ascii_case(name))
}
