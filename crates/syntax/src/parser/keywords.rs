//! The language's reserved words (design D1, D3 of `m2-procedures-and-errors`): the words the old compiler adds to
//! its name table as reserved before compiling (`qb64pe.bas`, "add reserved words to hashtable"). None of them can
//! name a variable or procedure (measured: each one as a variable name is rejected). A statement that starts with
//! one the parser does not handle gets a "not supported yet" error at parse time.
//!
//! Built-in SUB and function names (`CLS`, `LEN`) are not here: they come from the built-in table, which only
//! `sema` reads.

